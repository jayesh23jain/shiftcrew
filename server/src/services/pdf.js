import PDFDocument from 'pdfkit';

const collect = (doc) =>
  new Promise((resolve, reject) => {
    const chunks = [];
    doc.on('data', (c) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    doc.end();
  });

const inr = (p) => `Rs ${(p / 100).toFixed(2)}`;
const dt = (d) => new Date(d).toLocaleString('en-IN', { dateStyle: 'medium', timeStyle: 'short' });

export function receiptPdf({ payout, volunteerName, orgName, eventTitle }) {
  const doc = new PDFDocument({ size: 'A4', margin: 56 });
  doc.fontSize(22).text('Stipend payment receipt', { align: 'left' });
  doc.moveDown(0.3).fontSize(10).fillColor('#566275').text(`Receipt no. ${payout.receiptNo || 'pending'}`);
  doc.moveDown(1.5).fillColor('#101828').fontSize(12);
  const rows = [
    ['Paid to', volunteerName],
    ['Payment method', `UPI ${payout.upiMasked || ''}`],
    ['Event', eventTitle],
    ['Paid by', orgName],
    ['Date', payout.paidAt ? dt(payout.paidAt) : 'Not paid yet'],
    ['Status', payout.status.toUpperCase()],
    ['Amount', inr(payout.amount)],
  ];
  for (const [k, v] of rows) {
    doc.fillColor('#566275').fontSize(10).text(k);
    doc.fillColor('#101828').fontSize(13).text(String(v)).moveDown(0.6);
  }
  doc.moveDown().fontSize(9).fillColor('#566275')
    .text('Sandbox payment generated by ShiftCrew. This is a stipend, not salary, and carries no tax deduction.');
  return collect(doc);
}

export function certificatePdf({ cert }) {
  const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margin: 60 });
  const w = doc.page.width;
  doc.rect(30, 30, w - 60, doc.page.height - 60).lineWidth(2).stroke('#101828');
  doc.rect(30, 30, w - 60, 40).fill('#ffc93c');
  doc.fillColor('#101828').fontSize(14).text('CERTIFICATE OF VOLUNTEERING', 0, 44, { align: 'center' });
  doc.moveDown(4).fontSize(14).fillColor('#566275').text('This certifies that', { align: 'center' });
  doc.moveDown(0.5).fontSize(36).fillColor('#101828').text(cert.volunteerName, { align: 'center' });
  doc.moveDown(0.5).fontSize(14).fillColor('#566275')
    .text(`volunteered ${Math.floor(cert.minutes / 60)} hours ${cert.minutes % 60} minutes at`, { align: 'center' });
  doc.moveDown(0.4).fontSize(24).fillColor('#101828').text(cert.eventTitle, { align: 'center' });
  doc.moveDown(0.3).fontSize(13).fillColor('#566275').text(`organized by ${cert.orgName}`, { align: 'center' });
  doc.fontSize(10).text(`Issued ${dt(cert.createdAt)}   |   Verification code: ${cert.code}`, 0, doc.page.height - 90, { align: 'center' });
  return collect(doc);
}
